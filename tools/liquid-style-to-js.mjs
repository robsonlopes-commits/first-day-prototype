// Usage: node tools/liquid-style-to-js.mjs <in.liquid> <out.js> [--pre "js statements"] [--from "marker"] [--to "marker"] [--vars "a,b,c"]
// Turns the <style>/{% style %} block of a Shopify section/snippet into a JS function
//   export default function css(s, id, v) { ... return `...` }
// s = section settings object (same keys as the template JSON "settings"), id = section id, v = extra locals.
// Supports {{ expr | filters }}, if/elsif/else/endif, unless, comment (dropped). Liquid `assign` is NOT handled: pass them via --pre.
import fs from 'node:fs';

const args = process.argv.slice(2);
const [inFile, outFile] = args;
const opt = (name, dflt) => { const i = args.indexOf(name); return i > -1 ? args[i + 1] : dflt; };
const pre = opt('--pre', '');
const vars = opt('--vars', '');
let src = fs.readFileSync(inFile, 'utf8');

// cut the style block
const startM = opt('--from') ? new RegExp(opt('--from')) : /<style[^>]*>|\{%-?\s*style\s*-?%\}/;
const endM = opt('--to') ? new RegExp(opt('--to')) : /<\/style>|\{%-?\s*endstyle\s*-?%\}/;
const am = src.match(startM);
if (am) {
  src = src.slice(am.index + am[0].length);
  const e = src.search(endM);
  if (e > -1) src = src.slice(0, e);
}

const expr = (e) => {
  e = e.trim();
  const parts = e.split(/\s\|\s/);
  let base = parts.shift().trim();
  base = base.replace(/section\.settings\.(\w+)/g, 's.$1').replace(/\bsection\.id\b/g, 'id').replace(/\bsection_id\b/g, 'id');
  let out = base;
  for (const f of parts) {
    const [name, arg] = f.split(/:\s*/);
    const n = name.trim();
    const A = (arg || '').trim().replace(/section\.settings\.(\w+)/g, 's.$1');
    if (n === 'default') out = `(${out} || ${A})`;
    else if (n === 'times') out = `(${out} * ${A})`;
    else if (n === 'plus') out = `(${out} + ${A})`;
    else if (n === 'minus') out = `(${out} - ${A})`;
    else if (n === 'divided_by') out = `(${out} / ${A})`;
    else if (n === 'round') out = `Math.round(${out})`;
    else if (n === 'append') out = `(${out} + ${A})`;
    else if (n === 'strip' || n === 'escape' || n === 'strip_html') out = `String(${out})`;
    else if (n === 'image_url') out = `imgUrl(${out})`;
    else throw new Error(`unsupported filter ${n} in {{ ${e} }}`);
  }
  return out;
};
const cond = (c) => {
  let r = c.trim().replace(/section\.settings\.(\w+)/g, 's.$1').replace(/\bsection\.id\b/g, 'id');
  r = r.replace(/(\S+)\s*!=\s*blank/g, '!!$1').replace(/(\S+)\s*==\s*blank/g, '!$1');
  r = r.replace(/\band\b/g, '&&').replace(/\bor\b/g, '||').replace(/\s==\s/g, ' === ').replace(/\s!=\s/g, ' !== ');
  return r;
};

let out = '';
const stack = [];
const re = /\{%-?([\s\S]*?)-?%\}|\{\{-?([\s\S]*?)-?\}\}/g;
let last = 0;
let m;
const esc = (t) => t.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
let inComment = false;
while ((m = re.exec(src))) {
  const text = src.slice(last, m.index);
  last = re.lastIndex;
  if (!inComment) out += esc(text);
  if (m[2] !== undefined) { if (!inComment) out += '${' + expr(m[2]) + '}'; continue; }
  const tag = m[1].trim();
  const [kw, ...restArr] = tag.split(/\s+/);
  const rest = restArr.join(' ');
  if (kw === 'comment') { inComment = true; continue; }
  if (kw === 'endcomment') { inComment = false; continue; }
  if (inComment) continue;
  if (kw === 'if') { out += '${(' + cond(rest) + ') ? `'; stack.push({ hasElse: false }); }
  else if (kw === 'unless') { out += '${!(' + cond(rest) + ') ? `'; stack.push({ hasElse: false }); }
  else if (kw === 'elsif') { out += '` : (' + cond(rest) + ') ? `'; }
  else if (kw === 'else') { out += '` : `'; stack[stack.length - 1].hasElse = true; }
  else if (kw === 'endif' || kw === 'endunless') { const st = stack.pop(); out += st.hasElse ? '`}' : "` : ''}"; }
  else throw new Error(`unsupported tag {% ${tag} %}`);
}
out += esc(src.slice(last));
if (stack.length) throw new Error('unbalanced if');

const js = `// Generated by tools/liquid-style-to-js.mjs from ${inFile.split('reference/theme/')[1] || inFile}. s = section settings, id = section id.
import { shopImg } from '../lib/assets.js';
const imgUrl = (v) => (!v ? '' : String(v).startsWith('shopify://shop_images/') ? shopImg(String(v).slice(22)) : v);
/* eslint-disable no-unused-vars */
export default function css(s, id, v = {}) {
  ${vars ? `const { ${vars} } = v;` : ''}
  ${pre}
  return \`${out}\`;
}
`;
fs.writeFileSync(outFile, js);
console.log('wrote', outFile, out.length);
